{
  public static int ToItem(int style)
  {
    const int defaultItemId = 336;

    if (style >= 1 && style <= 10)
    {
      return 2071 + style;
    }

    if (style >= 11 && style <= 15)
    {
      return 2113 + style;
    }

    return style switch
    {
      16 => 2232,
      17 => 2519,
      18 => 2537,
      19 => 2552,
      20 => 2567,
      21 => 2658,
