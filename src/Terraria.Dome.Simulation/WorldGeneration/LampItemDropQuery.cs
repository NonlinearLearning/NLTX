namespace Terraria.Dome.Simulation.WorldGeneration;

public static class LampItemDropQuery
{
  public static int ToItem(int style)
  {
    const int defaultItemId = 342;

    if (style >= 1 && style <= 10)
    {
      return 2082 + style - 1;
    }

    if (style >= 11 && style <= 16)
    {
      return 2129 + style - 11;
    }

    return style switch
    {
      17 => 2225, 18 => 2533, 19 => 2547, 20 => 2563, 21 => 2578,
      22 => 2643, 23 => 2644, 24 => 2645, 25 => 2646, 26 => 2647,
      27 => 2819, 28 => 3135, 29 => 3137, 30 => 3136, 31 => 3892,
      32 => 3942, 33 => 3969, 34 => 4156, 35 => 4177, 36 => 4198,
      37 => 4219, 38 => 4308, 39 => 4577, 40 => 5159, 41 => 5180,
      42 => 5201, 43 => 5559, 44 => 5612, 45 => 5700, 46 => 5723,
      47 => 5748, 48 => 5767, 49 => 5788, 50 => 5809, 51 => 5830,
      52 => 5849, 53 => 5869, 54 => 5889, 55 => 5909, 56 => 5943,
      57 => 5966, 58 => 5986, 59 => 6009, 60 => 6032, 61 => 6055,
      62 => 6078, 63 => 6100, 64 => 6122,
      _ => defaultItemId
    };
  }
}
