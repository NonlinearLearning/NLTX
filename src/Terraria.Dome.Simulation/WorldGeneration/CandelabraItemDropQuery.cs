namespace Terraria.Dome.Simulation.WorldGeneration;

public static class CandelabraItemDropQuery
{
  public static int ToItem(int style)
  {
    const int defaultItemId = 349;

    if (style >= 1 && style <= 12)
    {
      return 2092 + style - 1;
    }

    if (style >= 13 && style <= 16)
    {
      return 2149 + style - 13;
    }

    return style switch
    {
      17 => 2227,
      18 => 2522,
      19 => 2541,
      20 => 2555,
      21 => 2570,
      22 => 2664,
      23 => 2665,
      24 => 2666,
      25 => 2667,
      26 => 2668,
      27 => 2825,
      28 => 3168,
      29 => 3170,
      30 => 3169,
      31 => 3893,
      32 => 3935,
      33 => 3961,
      34 => 4149,
      35 => 4170,
      36 => 4191,
      37 => 4212,
      38 => 4302,
      39 => 4570,
      40 => 5152,
      41 => 5173,
      42 => 5194,
      43 => 5552,
      44 => 5605,
      45 => 5693,
      46 => 5716,
      47 => 5742,
      48 => 5759,
      49 => 5780,
      50 => 5801,
      51 => 5822,
      52 => 5843,
      53 => 5861,
      54 => 5882,
      55 => 5901,
      56 => 5935,
      57 => 5958,
      58 => 5978,
      59 => 6001,
      60 => 6024,
      61 => 6047,
      62 => 6070,
      63 => 6093,
      64 => 6114,
      _ => defaultItemId
    };
  }
}
