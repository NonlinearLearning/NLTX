  /// <summary>False means unsupported, not CanShimmer=false.</summary>
  public static bool TryGetDirectTransform(int itemType, out int targetType)
  {
    targetType = 0;
    // ShimmerTransforms.IsItemTransformLocked: these require captured Moonlord state.
    if (itemType is 1326 or 779 or 3031 or 5364 or 784 or 782)
    {
      return false;
    }

    // GetTransformToItem checks the direct table before tile-139 music boxes.
    if (s_directTransforms.TryGetValue(itemType, out targetType))
    {
      return true;
    }

    if (ItemContentFacts.IsPlacedMusicBox(itemType))
    {
      targetType = itemType switch {
        5579 => 5538,
        5538 => 5579,
        5639 => 5638,
        5638 => 5639,
        _ => 576
      };
      return true;
    }

    // Counts-as aliases, recipe, NPC and coin paths still need captured facts.
    return false;
  }

  public static bool TryGetTransform(int itemType, byte moonPhase, out int targetType)
  {
    if (itemType != 3461)
    {
      return TryGetDirectTransform(itemType, out targetType);
    }

    // Complete ShimmerTransforms.GetLunarBrickTransformFromMoonPhase;
    // MoonPhase has identical values 0..7 in Version4 and the complete source.
    targetType = moonPhase switch {
      0 => 5408,
      1 => 5401,
      2 => 5403,
      3 => 5402,
      4 => 5406,
      5 => 5407,
      6 => 5405,
      7 => 5404,
      _ => 0
    };
    return targetType != 0;
  }

  public static bool IsSupportedTransform(int sourceType, int targetType)
  {
    // The tick participant binds the precise lunar target to its captured world revision.
    return sourceType == 3461 ? targetType is >= 5401 and <= 5408
      : TryGetDirectTransform(sourceType, out int expected) && expected == targetType;
  }
